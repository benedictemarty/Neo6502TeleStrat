def glyph_rows(first, rows):
    g = [B] * 8
    for i, r in enumerate(rows):
        g[first + i] = r
    return g


def build():
    font = {}
    for ch, rows in CAPS.items():
        font[ch] = glyph_rows(1, rows)
    for ch, (first, rows) in list(LOWER.items()) + list(PUNCT.items()):
        font[ch] = glyph_rows(first, rows)
    font["ı"] = glyph_rows(*DOTLESS_I)
    for ch, (base, acc) in ACCENTS.items():
        g = list(font[base])
        if base.isupper():
            g[0] = ACC_UPPER[acc]
        else:
            g[0], g[1] = ACC_LOWER[acc]
        font[ch] = g
    font["ç"] = list(font["c"])
    font["ç"][7] = "...##..."
    font["Ç"] = list(font["C"])
    font["Ç"][7] = "...##..."
    table = [[B] * 8 for _ in range(256)]
    for ch, g in font.items():
        code = ord(ch)
        if code < 256:
            table[code] = g
    for i, (_, g) in enumerate(ICONES):
        table[0x80 + i] = g
    for code, g in enumerate(table):
        assert len(g) == 8 and all(len(r) == 8 for r in g), (code, g)
    return table


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/osd/osd_font.h"
    table = build()
    with open(out, "w") as f:
        f.write("#pragma once\n\n// osd_font.h — généré par tools/gen_osd_font.py (dessin original, 8 x 8,\n"
                "// bit 0 = pixel de gauche). Ne pas modifier à la main.\n\n#include <stdint.h>\n\n")
        for i, (name, _) in enumerate(ICONES):
            f.write("#define OSD_%-8s 0x%02X\n" % (name, 0x80 + i))
        f.write("\n// Section de la police (le firmware la met en RAM, lue par le cœur 1)\n"
                "#ifndef OSD_FONT_SECTION\n#define OSD_FONT_SECTION\n#endif\n")
        f.write("\nstatic const uint8_t OSD_FONT_SECTION osd_font[256][8] = {\n")
        for code, g in enumerate(table):
            vals = [sum(1 << x for x in range(8) if r[x] == "#") for r in g]
            f.write("    {%s},  // 0x%02X\n" % (", ".join("0x%02X" % v for v in vals), code))
        f.write("};\n")
    if len(sys.argv) > 2:
        from PIL import Image
        img = Image.new("RGB", (16 * 10, 16 * 20), (0, 0, 0))
        px = img.load()
        for code in range(256):
            cx, cy = code % 16 * 10, code // 16 * 20
            for y in range(8):
                for x in range(8):
                    if table[code][y][x] == "#":
                        px[cx + x, cy + 2 * y] = px[cx + x, cy + 2 * y + 1] = (255, 255, 255)
        img.resize((img.width * 3, img.height * 3), Image.NEAREST).save(sys.argv[2])


if __name__ == "__main__":
    main()
